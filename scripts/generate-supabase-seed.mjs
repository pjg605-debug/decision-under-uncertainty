import { readFile, writeFile } from 'node:fs/promises';
import { runInNewContext } from 'node:vm';
import ts from 'typescript';

const root = new URL('../', import.meta.url);
const sourceUrl = new URL('../data/cases.ts', import.meta.url);
let source = await readFile(sourceUrl, 'utf8');

source = source.replace(/^import type .*?;\r?\n/m, '');
const narrativeImports = [
  ...source.matchAll(/^import (\w+) from ['"](.+?\.json)['"];?$/gm),
];
for (const match of narrativeImports) {
  const json = JSON.parse(await readFile(new URL(match[2], sourceUrl), 'utf8'));
  source = source.replace(
    match[0],
    `const ${match[1]} = ${JSON.stringify(json)};`,
  );
}
source = source.replaceAll('export const ', 'const ');
source += '\nglobalThis.__seedBundle = { cases, narratives };';

const compiled = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.None,
  },
}).outputText;
const sandbox = {};
runInNewContext(compiled, sandbox);
const bundle = sandbox.__seedBundle;

const lit = (value) =>
  value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const json = (value) => `${lit(JSON.stringify(value))}::jsonb`;
const num = (value, fallback = 50) =>
  Number.isFinite(value) ? Math.round(value) : fallback;
const tuple = (values) => `(${values.join(', ')})`;

const statements = [
  '-- Generated by scripts/generate-supabase-seed.mjs. Do not edit by hand.',
  '-- Re-running this seed replaces only the six bundled MVP cases and their child rows.',
  'begin;',
];

for (const decisionCase of bundle.cases) {
  const c = decisionCase;
  statements.push(`insert into public.decision_cases (
    case_key,title,domain,subdomain,actor,actor_role,date_or_period,era,location,t0,context_summary,
    actual_decision_key,immediate_outcome,long_term_outcome,decision_quality,outcome_quality,
    popularity,controversy_risk,context_compression,visualizability,source_disagreement,
    uncertainty_factors,metadata,progressive,narrative_key,status,fame_score,research_priority
  ) values ${tuple([
    lit(c.id),
    lit(c.title),
    lit(c.domain),
    lit(c.subdomain),
    lit(c.actor),
    lit(c.actor_role),
    lit(c.date_or_period),
    lit(c.era),
    lit(c.location),
    lit(c.t0),
    lit(c.context_summary),
    lit(
      String.fromCharCode(
        65 + c.options.findIndex((option) => option.id === c.actual_decision),
      ),
    ),
    lit(c.immediate_outcome),
    lit(c.long_term_outcome),
    lit(c.decision_quality),
    lit(c.outcome_quality),
    String(num(c.metadata?.popularity)),
    String(num(c.metadata?.controversy_risk, 0)),
    String(num(c.metadata?.context_compression)),
    String(num(c.metadata?.visualizability)),
    String(num(c.metadata?.source_disagreement, 0)),
    json(c.uncertainty_factors),
    json(c.metadata),
    c.progressive ? json(c.progressive) : 'null',
    lit(c.narrative_id),
    lit('APPROVED'),
    String(num(c.metadata?.popularity)),
    String(num(c.scores?.evidence)),
  ])}
  on conflict (case_key) do update set
    title=excluded.title, domain=excluded.domain, subdomain=excluded.subdomain, actor=excluded.actor,
    actor_role=excluded.actor_role, date_or_period=excluded.date_or_period, era=excluded.era,
    location=excluded.location, t0=excluded.t0, context_summary=excluded.context_summary,
    actual_decision_key=excluded.actual_decision_key, immediate_outcome=excluded.immediate_outcome,
    long_term_outcome=excluded.long_term_outcome, decision_quality=excluded.decision_quality,
    outcome_quality=excluded.outcome_quality, uncertainty_factors=excluded.uncertainty_factors,
    popularity=excluded.popularity, controversy_risk=excluded.controversy_risk,
    context_compression=excluded.context_compression, visualizability=excluded.visualizability,
    source_disagreement=excluded.source_disagreement,
    metadata=excluded.metadata, progressive=excluded.progressive, narrative_key=excluded.narrative_key,
    fame_score=excluded.fame_score, research_priority=excluded.research_priority, updated_at=now();`);
}

const keys = bundle.cases.map((c) => lit(c.id)).join(', ');
statements.push(`
delete from public.status_transitions where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.agent_runs where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.research_gaps where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.research_claims where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.revisions where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.reviews where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.publication_results where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.shorts_variants where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.narratives where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.case_scores where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.evidence where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.case_information where case_id in (select id from public.decision_cases where case_key in (${keys}));
delete from public.decision_options where case_id in (select id from public.decision_cases where case_key in (${keys}));`);

for (const c of bundle.cases) {
  const caseId = `(select id from public.decision_cases where case_key=${lit(c.id)})`;
  c.options.forEach((o, index) =>
    statements.push(
      `insert into public.decision_options (case_id,option_key,decision_key,sort_order,label,short_description,upside,downside,known_tradeoffs) values ${tuple([caseId, lit(String.fromCharCode(65 + index)), lit(o.id), String(index + 1), lit(o.label), lit(o.short_description), lit(o.upside), lit(o.downside), json(o.known_tradeoffs)])};`,
    ),
  );
  c.known_information.forEach((content, index) =>
    statements.push(
      `insert into public.case_information (case_id,information_type,sequence,content) values ${tuple([caseId, lit('KNOWN_AT_T0'), String(index + 1), lit(content)])};`,
    ),
  );
  c.unknown_information.forEach((content, index) =>
    statements.push(
      `insert into public.case_information (case_id,information_type,sequence,content) values ${tuple([caseId, lit('UNKNOWN_AT_T0'), String(index + 1), lit(content)])};`,
    ),
  );
  if (c.progressive)
    statements.push(
      `insert into public.case_information (case_id,information_type,sequence,content) values ${tuple([caseId, lit('PROGRESSIVE_EVIDENCE'), '1', lit(c.progressive.evidence)])};`,
    );

  let sources = c.evidence;
  try {
    sources = JSON.parse(
      await readFile(
        new URL(`../data/evidence/${c.id}.json`, import.meta.url),
        'utf8',
      ),
    ).sources;
  } catch {}
  for (const e of sources) {
    statements.push(
      `insert into public.evidence (case_id,evidence_key,source_type,title,author_or_institution,publication_date,url,accessed_at,citation,evidence_class,supported_claim,source_quality,source_disagreement) values ${tuple(
        [
          caseId,
          lit(e.id),
          lit(e.source_type),
          lit(e.title),
          lit(e.author_or_institution),
          lit(e.publication_date),
          lit(e.url || null),
          e.accessed_at ? lit(e.accessed_at) : 'null',
          lit(e.citation || null),
          lit(e.evidence_class),
          lit(
            Array.isArray(e.supports)
              ? e.supports.join(' | ')
              : e.supported_claim || null,
          ),
          String(e.source_quality ?? c.scores?.evidence ?? 70),
          String(e.source_disagreement ?? c.metadata?.source_disagreement ?? 0),
        ],
      )};`,
    );
  }

  const q = c.scores;
  const production = bundle.narratives[c.narrative_id] || {};
  const evals = production.evaluations || {};
  const fairness =
    evals.PLAYER_FAIRNESS?.score ??
    Math.min(100, num(c.metadata?.context_compression) + 5);
  const balance = evals.DILEMMA_BALANCE?.score ?? num(c.scores?.decision);
  const compression =
    evals.CONTEXT_COMPRESSION?.score ?? num(c.metadata?.context_compression);
  const payoff = evals.REVEAL_PAYOFF?.score ?? num(c.scores?.mystery);
  const shortsPotential = Math.round(
    (q.curiosity +
      q.decision +
      q.stakes +
      q.mystery +
      q.explainability +
      q.evidence) /
      6,
  );
  statements.push(
    `insert into public.case_scores (case_id,curiosity,decision,stakes,mystery,explainability,evidence,player_fairness,dilemma_balance,context_compression,reveal_payoff,scorer,scoring_version,shorts_potential,notes) values ${tuple(
      [
        caseId,
        String(q.curiosity),
        String(q.decision),
        String(q.stakes),
        String(q.mystery),
        String(q.explainability),
        String(q.evidence),
        String(fairness),
        String(balance),
        String(compression),
        String(payoff),
        lit('codex'),
        lit('1.0'),
        String(shortsPotential),
        lit(
          'Migrated unchanged from the local DecisionEvent fixture and narrative evaluation.',
        ),
      ],
    )};`,
  );

  const a = c.options[0];
  const b = c.options[1];
  const narrative = {
    hook: production.hook || c.title,
    short_setup: production.short_setup || c.context_summary,
    why_option_a_made_sense:
      production.why_option_a_made_sense ||
      `${a.label} offered ${a.upside.toLowerCase()}, while accepting ${a.downside.toLowerCase()}.`,
    why_option_b_made_sense:
      production.why_option_b_made_sense ||
      `${b.label} offered ${b.upside.toLowerCase()}, while accepting ${b.downside.toLowerCase()}.`,
    actual_decision_explanation:
      production.actual_decision_explanation ||
      `The historical actor selected ${c.options.find((o) => o.id === c.actual_decision)?.label}.`,
    outcome_story:
      production.outcome_story ||
      `${c.immediate_outcome} ${c.long_term_outcome}`,
    hindsight_analysis:
      production.hindsight_analysis ||
      'Decision quality should be assessed from the evidence and constraints available at T0, independently from the outcome.',
    decision_principle:
      production.decision_principle ||
      'Judge the process with the information available at the time.',
    longform_story:
      production.longform_story ||
      `${c.context_summary}\n\n${c.immediate_outcome}\n\n${c.long_term_outcome}`,
    evidence_refs: production.evidence_refs || sources.map((e) => e.id),
    evaluations: production.evaluations || {
      migrated_fixture: { status: 'NEEDS_EDITORIAL_REVIEW' },
    },
  };
  const version = c.id === 'cuban-missile-1962' ? 2 : 1;
  if (version === 2) {
    statements.push(
      `insert into public.narratives (case_id,narrative_key,version,status,author_agent,hook,short_setup,why_option_a_made_sense,why_option_b_made_sense,actual_decision_explanation,outcome_story,hindsight_analysis,decision_principle,longform_story,evidence_refs,quality_evaluations,revision_summary,is_current) values ${tuple(
        [
          caseId,
          lit(c.narrative_id),
          '1',
          lit('ARCHIVED'),
          lit('claude'),
          lit(narrative.hook),
          lit(narrative.short_setup),
          lit(narrative.why_option_a_made_sense),
          lit(narrative.why_option_b_made_sense),
          lit(narrative.actual_decision_explanation),
          lit(narrative.outcome_story),
          lit(narrative.hindsight_analysis),
          lit(narrative.decision_principle),
          lit(narrative.longform_story),
          json(narrative.evidence_refs),
          json(narrative.evaluations),
          lit('Initial narrative submitted for integration-loop validation.'),
          'false',
        ],
      )};`,
    );
  }
  statements.push(
    `insert into public.narratives (case_id,narrative_key,version,status,author_agent,hook,short_setup,why_option_a_made_sense,why_option_b_made_sense,actual_decision_explanation,outcome_story,hindsight_analysis,decision_principle,longform_story,evidence_refs,quality_evaluations,revision_summary,is_current) values ${tuple(
      [
        caseId,
        lit(c.narrative_id),
        String(version),
        lit('APPROVED'),
        lit(version === 2 ? 'claude' : 'codex-migration'),
        lit(narrative.hook),
        lit(narrative.short_setup),
        lit(narrative.why_option_a_made_sense),
        lit(narrative.why_option_b_made_sense),
        lit(narrative.actual_decision_explanation),
        lit(narrative.outcome_story),
        lit(narrative.hindsight_analysis),
        lit(narrative.decision_principle),
        lit(narrative.longform_story),
        json(narrative.evidence_refs),
        json(narrative.evaluations),
        lit(
          version === 2
            ? 'Revision completed after Codex integration review.'
            : 'Initial fixture migration.',
        ),
        'true',
      ],
    )};`,
  );

  const frames = [
    { at: '0-2', label: 'HOOK', text: narrative.hook },
    { at: '2-8', label: 'CONTEXT', text: narrative.short_setup },
    {
      at: '8-13',
      label: 'A/B',
      text: c.options.map((o) => o.label).join(' vs '),
    },
    {
      at: '16-25',
      label: 'ACTUAL DECISION',
      text: narrative.actual_decision_explanation,
    },
    { at: '25-32', label: 'OUTCOME', text: c.immediate_outcome },
  ];
  const currentNarrativeId = `(select id from public.narratives where case_id=${caseId} and is_current limit 1)`;
  statements.push(
    `insert into public.shorts_variants (case_id,narrative_id,version,status,author_agent,duration_target,script,storyboard,hook_variant) values ${tuple([caseId, currentNarrativeId, '1', lit('APPROVED'), lit('codex-migration'), lit('30_40'), lit(frames.map((frame) => frame.text).join(' ')), json(frames), lit(narrative.hook)])};`,
  );
}

statements.push(`
with sample as (
  select c.id as case_id, n.id as narrative_id
  from public.decision_cases c
  join public.narratives n on n.case_id=c.id and n.version=1
  where c.case_key='cuban-missile-1962'
), review_insert as (
  insert into public.reviews (case_id,narrative_id,reviewer_agent,review_type,field_name,severity,status,verdict,comment,suggested_change,findings,resolved_at)
  select case_id,narrative_id,'codex','OTHER','outcome_story','MEDIUM','RESOLVED','REVISE','Integration feedback-loop validation: preserve T0 fairness and make the private settlement explicit.',
         'Separate the public pledge from the private Jupiter understanding.',
         '[{"field":"outcome_story","request":"Separate the public pledge from the private Jupiter understanding."}]'::jsonb,now()
  from sample returning id,case_id
)
insert into public.revisions (case_id,narrative_id,triggered_by_review_id,author_agent,before_version,after_version,summary,changes)
select r.case_id,n.id,r.id,'claude',1,2,'Resolved the Codex review request and submitted narrative version 2.',
       '[{"field":"outcome_story","change":"Clarified public and private settlement channels."}]'::jsonb
from review_insert r join public.narratives n on n.case_id=r.case_id and n.version=2;

insert into public.status_transitions (case_id,from_status,to_status,actor_agent,reason)
select id,step.from_status,step.to_status,step.agent,step.reason
from public.decision_cases
cross join (values
  ('RESEARCH_DONE','NARRATIVE_DRAFTED','claude','Narrative v1 submitted'),
  ('NARRATIVE_DRAFTED','CODEX_REVIEW','codex','Review opened'),
  ('CODEX_REVIEW','REVISION_REQUESTED','codex','Revision requested'),
  ('REVISION_REQUESTED','REVISION_DONE','claude','Narrative v2 submitted'),
  ('REVISION_DONE','APPROVED','codex','Revision verified')
) as step(from_status,to_status,agent,reason)
where case_key='cuban-missile-1962';

commit;`);

await writeFile(
  new URL('../supabase/seed.sql', import.meta.url),
  `${statements.join('\n\n')}\n`,
);
console.log(`Generated supabase/seed.sql for ${bundle.cases.length} cases.`);
